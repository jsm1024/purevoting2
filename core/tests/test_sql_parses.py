"""The init SQL and the smoke test must parse as PostgreSQL, including the PL/pgSQL bodies.
(The real execution is checked by the core-db CI job against a PostgreSQL service.)"""
from pathlib import Path

import pytest

pglast = pytest.importorskip("pglast")

DB = Path(__file__).resolve().parents[1] / "db"
FILES = [DB / "init" / "10_schema.sql", DB / "tests" / "smoke.sql"]


def _statements(path):
    # psql meta-commands (\set …) and comment lines are not SQL
    lines = [l for l in path.read_text(encoding="utf-8").splitlines()
             if not l.lstrip().startswith(("\\", "--"))]
    src = "\n".join(lines)
    raw = src.encode("utf-8")
    for s in pglast.parse_sql(src):
        end = s.stmt_location + s.stmt_len if s.stmt_len else len(raw)
        yield raw[s.stmt_location:end].decode("utf-8").strip()


@pytest.mark.parametrize("path", FILES, ids=lambda p: p.name)
def test_sql_and_plpgsql_parse(path):
    stmts = list(_statements(path))
    assert stmts
    for stmt in stmts:
        words = stmt.split()
        if words[0].upper() == "DO" or (words[0].upper() == "CREATE" and words[1].upper() == "FUNCTION"):
            pglast.parse_plpgsql(stmt + ";")


def test_no_serial_or_identity_columns():
    # gap-free seq and random voter-side keys (README "Shared conventions", "Consistency model")
    lines = (DB / "init" / "10_schema.sql").read_text(encoding="utf-8").lower().splitlines()
    sql = "\n".join(l.split("--")[0] for l in lines)
    for forbidden in ("serial", "generated always as identity", "generated by default as identity", "create sequence"):
        assert forbidden not in sql
